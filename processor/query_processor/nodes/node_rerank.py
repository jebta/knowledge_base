from processor.query_processor.base import NodeBase
from processor.query_processor.state import QueryGraphState
from tool.json_format import json_format
from tool.logger import logger
from tool.rerank_utils import text_rerank


class NodeRerank(NodeBase):
    """
    节点功能：使用 Cross-Encoder 模型对 RRF 后的结果进行精确打分重排。
    """

    # 覆盖基类的 name 属性，标识节点名称
    name: str = "node_rerank"

    def process(self, state: QueryGraphState):
        """
        节点逻辑
        :param state: 工作流状态对象
        :return: 更新后的状态对象
        """
        rewritten_query = state.get("rewritten_query")
        rrf_chunks = state.get("rrf_chunks")
        web_search_docs = state.get("web_search_docs")
        merged_chunks = rrf_chunks + web_search_docs
        chunks = []
        for chunk in merged_chunks:
            chunks.append({
                "content": chunk.get("content", ""),
                "source": chunk.get("source", ""),
                "url": chunk.get("url", ""),
                "title": chunk.get("title") or chunk.get("file_title"),
            })

        chunks_content = [chunk.get("content") for chunk in chunks]
        results = text_rerank(rewritten_query, chunks_content, limit=len(chunks))
        for item in results:
            chunks[item.get("index")]["score"] = item.get("score")

        chunks = sorted(chunks, key=lambda x: x["score"], reverse=True)

        # 动态 TopK：硬上限：最多取前 N 条（<=10）
        RERANK_MAX_TOPK: int = 10
        # 最小 TopK：至少保留前 N 条（>=1，且 <= RERANK_MAX_TOPK）
        RERANK_MIN_TOPK: int = 3  # 总数最少条数
        # 断崖阈值（相对）
        RERANK_GAP_RATIO: float = 0.25
        # 断崖阈值（绝对）
        RERANK_GAP_ABS: float = 0.10

        use_max_topk = min(RERANK_MAX_TOPK, len(chunks))
        use_min_topk = min(use_max_topk, RERANK_MIN_TOPK)
        break_point = use_min_topk
        for i in range(use_min_topk - 1, use_max_topk - 1):
            current_score = chunks[i].get("score")
            next_score = chunks[i + 1].get("score")
            abs_gap = abs(current_score - next_score)
            ratio_gap = abs_gap / (current_score + 1e-6)
            if abs_gap > RERANK_GAP_ABS or ratio_gap > RERANK_GAP_RATIO:
                break_point = i + 1
                break

        return {
            "reranked_docs": chunks[:break_point]
        }


